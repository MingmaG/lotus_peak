/**
 * Substitutes `{{token}}`.
 *
 * An unknown token is replaced with an empty string rather than left in place.
 * Leaving it renders `{{deparutre}}` to a customer; removing it renders a
 * sentence with a gap, which is the better of the two failures — and the
 * editor already refused to save it.
 */
export function fill(text: string, values: Record<string, string>): string {
  return text.replace(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g, (_match, key: string) =>
    values[key] ?? '',
  );
}

