/**
 * The words an enquiry turns into, and the HTML they are rendered in.
 *
 * A package rather than a file in the admin panel for the same reason the SEO
 * graph is one: the office edits these templates in a screen that must show
 * what will actually be sent. One renderer, called by the admin to preview and
 * by whichever app delivers, means the preview cannot drift from the message.
 *
 * ## Why the templates are rows and not files
 *
 * "Thank you for writing to us" is copy, and copy is the office's, not the
 * developer's. Every field here may carry tokens — `{{name}}`, `{{trip}}` —
 * and the token list is fixed per kind, so an editor can rewrite the whole
 * message without a deploy and cannot reference a variable that does not
 * exist.
 *
 * ## Why the HTML looks like 2004
 *
 * Tables, inline styles, no flexbox, no custom properties. Not taste: Outlook
 * on Windows renders through Word, which supports none of it. The design
 * system's tokens are resolved to literal hex values *here*, at the one
 * boundary where the rule against hardcoded colours does not apply, because
 * the alternative is an email that arrives unstyled.
 */

export type EmailKind =
  | 'ENQUIRY_ACKNOWLEDGEMENT'
  | 'ENQUIRY_NOTIFICATION'
  | 'NEWSLETTER_WELCOME'
  | 'NEWSLETTER_CONFIRM'
  | 'PASSWORD_RESET';

/** The words one kind of message is made of. Every field may carry tokens. */
export interface EmailTemplate {
  kind: EmailKind;
  name: string;
  isActive: boolean;
  subject: string;
  /** The line the inbox shows after the subject. Never rendered in the body. */
  preheader: string;
  eyebrow: string;
  heading: string;
  /** Blank lines separate paragraphs. */
  intro: string;
  closing: string;
  summaryLabel: string;
  notesLabel: string;
  buttonLabel: string;
  /** Relative to the site, or absolute. Blank hides the button. */
  buttonUrl: string;
  signOff: string;
  footNote: string;
}

/** Who is sending, resolved from the one company record. */
export interface EmailIdentity {
  name: string;
  email: string;
  phone: string;
  siteUrl: string;
  addressLine: string;
  /** Absolute URL to a small logo, or blank. */
  logoUrl: string;
}

/** The enquiry a message is about, as the renderer reads it. */
export interface EmailEnquiry {
  reference: string;
  name: string;
  email: string;
  phone?: string;
  country?: string;
  tripTitle?: string;
  preferredDates?: string;
  travellers?: string;
  message?: string;
  restDays?: boolean;
  source?: string;
  /**
   * An operational note to the office, drawn above everything else.
   *
   * Not copy, and deliberately not editable: it says something about this
   * message that the office must not be able to switch off — at present, that
   * the enquiry reached nobody's inbox but this one, because the panel could
   * not be reached to record it. An enquiry that exists only as an email looks
   * exactly like one that is safely in the system, and that is how a lead is
   * lost twice.
   *
   * Ignored on the traveller's copy, which is not the place for it.
   */
  notice?: string;
  origin?: {
    pagePath?: string;
    utmSource?: string;
    utmMedium?: string;
    utmCampaign?: string;
  };
}

export interface RenderedEmail {
  subject: string;
  html: string;
  /**
   * The plain-text alternative.
   *
   * Not optional and not generated by stripping tags from the HTML. A
   * multipart message without one is scored as spam by most filters, and a
   * text part made by regex over a table layout is a column of stray
   * whitespace.
   */
  text: string;
}

