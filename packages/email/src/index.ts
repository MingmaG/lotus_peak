export interface RenderEnquiryArgs {
  template: EmailTemplate;
  identity: EmailIdentity;
  enquiry: EmailEnquiry;
  /** The office's copy carries the contact details and the attribution. */
  audience: 'traveller' | 'office';
  replyPromise?: string;
}

export function renderEnquiryEmail(args: RenderEnquiryArgs): RenderedEmail {
  const { template, identity, enquiry, audience } = args;

  const values: Record<string, string> = {
    name: enquiry.name,
    firstName: enquiry.name.split(' ')[0] ?? enquiry.name,
    reference: enquiry.reference,
    trip: enquiry.tripTitle ?? '',
    dates: enquiry.preferredDates ?? '',
    travellers: enquiry.travellers ?? '',
    country: enquiry.country ?? '',
    contactEmail: enquiry.email,
    contactPhone: enquiry.phone ?? '',
    source: enquiry.source ?? '',
    company: identity.name,
    phone: identity.phone,
    email: identity.email,
    siteUrl: identity.siteUrl,
    replyPromise: args.replyPromise ?? '',
  };

  const rows: [string, string][] = [
    ['Reference', enquiry.reference],
    ['Journey', enquiry.tripTitle ?? 'Not yet chosen'],
    ['When', enquiry.preferredDates ?? 'Flexible'],
    ['Travellers', enquiry.travellers ?? ''],
  ];

  if (audience === 'office') {
    rows.push(
      ['Name', enquiry.name],
      ['Email', enquiry.email],
      ['Phone', enquiry.phone ?? ''],
      ['Country', enquiry.country ?? ''],
      ['Rest days', enquiry.restDays ? 'Wanted' : ''],
      ['Form', enquiry.source ?? ''],
      ['Page', enquiry.origin?.pagePath ?? ''],
      ['Campaign', enquiry.origin?.utmCampaign ?? ''],
    );
  }

  const summaryLabel = fill(template.summaryLabel, values);
  const notesLabel = fill(template.notesLabel, values);

  const body = [
    audience === 'office' && enquiry.notice ? banner(enquiry.notice) : '',
    paragraphs(fill(template.intro, values)),
    summaryLabel ? heading(summaryLabel) : '',
    summaryTable(rows),
    enquiry.message ? heading(notesLabel || 'In their words') : '',
    enquiry.message
      ? `<div style="padding:16px 20px;background:${C.paper2};border-left:2px solid ${C.gold};margin:0 0 24px;"><p style="margin:0;font-size:15px;line-height:1.65;color:${C.ink};">${escapeHtml(
          enquiry.message,
        ).replace(/\n/g, '<br>')}</p></div>`
      : '',
    button(fill(template.buttonLabel, values), resolveUrl(identity, fill(template.buttonUrl, values))),
    paragraphs(fill(template.closing, values)),
    template.signOff
      ? `<p style="margin:0 0 24px;font-size:16px;line-height:1.65;color:${C.ink};">${escapeHtml(
          fill(template.signOff, values),
        ).replace(/\n/g, '<br>')}</p>`
      : '',
  ].join('');

  return {
    /**
     * Whitespace closed up after substitution, not before.
     *
     * `Enquiry {{reference}} — {{name}}` with no reference is
     * `Enquiry  — Anne Traveller`, and a subject line is the one place a
     * doubled space is conspicuous. Only the subject is treated this way: the
     * body's blank lines are paragraphs.
     */
    subject: fill(template.subject, values).replace(/\s+/g, ' ').trim(),
    html: shell({
      identity,
      preheader: fill(template.preheader, values),
      eyebrow: fill(template.eyebrow, values),
      heading: fill(template.heading, values),
      body,
      footNote: fill(template.footNote, values),
    }),
    text: plainText({
      notice: audience === 'office' ? enquiry.notice : undefined,
      heading: fill(template.heading, values),
      intro: fill(template.intro, values),
      rows,
      message: enquiry.message,
      closing: fill(template.closing, values),
      signOff: fill(template.signOff, values),
      identity,
    }),
  };
}

/**
 * The one thing in the message that is louder than the message.
 *
 * Saffron rather than gold, and a solid rule rather than a tint, because it is
 * read by somebody scanning a familiar email for what is new in it.
 */
function banner(text: string): string {
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:0 0 24px;"><tr><td style="padding:14px 18px;background:#FDF4E7;border-left:4px solid ${C.saffron};"><p style="margin:0;font-size:15px;line-height:1.55;font-weight:500;color:${C.ink};">${escapeHtml(
    text,
  )}</p></td></tr></table>`;
}

function heading(text: string): string {
  return `<h2 style="margin:28px 0 12px;font-size:13px;letter-spacing:0.16em;text-transform:uppercase;font-weight:500;color:${C.gold};">${escapeHtml(
    text,
  )}</h2>`;
}

function resolveUrl(identity: EmailIdentity, url: string): string {
  if (!url) return '';
  if (/^https?:\/\//i.test(url) || url.startsWith('mailto:') || url.startsWith('tel:')) {
    return url;
  }
  return `${identity.siteUrl.replace(/\/$/, '')}${url.startsWith('/') ? url : `/${url}`}`;
}

/** Written from the same inputs as the HTML, never derived from it. */
function plainText(args: {
  notice?: string;
  heading: string;
  intro: string;
  rows: [string, string][];
  message?: string;
  closing: string;
  signOff: string;
  identity: EmailIdentity;
}): string {
  const lines: string[] = [];
  /* Before the heading, not after it: the plain-text part is what a phone
     notification and every screen reader quote first. */
  if (args.notice) lines.push(`** ${args.notice} **`, '');
  lines.push(args.heading, '='.repeat(args.heading.length), '');
  if (args.intro) lines.push(args.intro, '');
  for (const [label, value] of args.rows) {
    if (value && value.trim()) lines.push(`${label}: ${value}`);
  }
  lines.push('');
  if (args.message) lines.push('In their words:', args.message, '');
  if (args.closing) lines.push(args.closing, '');
  if (args.signOff) lines.push(args.signOff, '');
  lines.push(
    '--',
    ...[
      args.identity.name,
      args.identity.addressLine,
      [args.identity.phone, args.identity.email].filter(Boolean).join(' · '),
      args.identity.siteUrl,
    ].filter(Boolean),
  );
  return lines.join('\n');
}

