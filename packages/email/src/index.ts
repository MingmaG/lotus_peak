/**
 * The design tokens, resolved.
 *
 * The one place in this repository where a hex literal is correct. These are
 * the published values of `--ink`, `--paper`, `--paper-2`, `--gold`,
 * `--saffron`, `--pine` and `--line`; when a token changes, this changes with
 * it, and the comment is the reminder that it has to be done by hand.
 */
const C = {
  ink: '#1A1A18',
  muted: '#6B6B66',
  paper: '#FFFFFF',
  paper2: '#F7F7F6',
  line: '#E4E2DD',
  gold: '#B08A44',
  saffron: '#D9770F',
  pine: '#1F3229',
} as const;

const FONT =
  "'Commissioner', -apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif";

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** Blank-line-separated prose → paragraphs. */
function paragraphs(text: string): string {
  return text
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .filter(Boolean)
    .map(
      (p) =>
        `<p style="margin:0 0 16px;font-size:16px;line-height:1.65;color:${C.ink};">${escapeHtml(
          p,
        ).replace(/\n/g, '<br>')}</p>`,
    )
    .join('');
}

function summaryTable(rows: [string, string][]): string {
  const cells = rows
    .filter(([, value]) => value && value.trim().length > 0)
    .map(
      ([label, value]) => `
        <tr>
          <td style="padding:10px 16px 10px 0;font-size:13px;letter-spacing:0.06em;text-transform:uppercase;color:${C.muted};border-bottom:1px solid ${C.line};white-space:nowrap;vertical-align:top;">${escapeHtml(
            label,
          )}</td>
          <td style="padding:10px 0;font-size:15px;line-height:1.5;color:${C.ink};border-bottom:1px solid ${C.line};">${escapeHtml(
            value,
          )}</td>
        </tr>`,
    )
    .join('');

  if (!cells) return '';
  return `<table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%" style="border-collapse:collapse;margin:0 0 24px;">${cells}</table>`;
}

/**
 * The shell every message is drawn in.
 *
 * 600 px, centred, one column. `width` attributes as well as CSS because
 * Outlook ignores the second; `role="presentation"` so a screen reader does
 * not announce the layout as four nested tables.
 */
function shell(args: {
  identity: EmailIdentity;
  preheader: string;
  eyebrow: string;
  heading: string;
  body: string;
  footNote: string;
}): string {
  const { identity } = args;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="x-apple-disable-message-reformatting">
<title>${escapeHtml(args.heading)}</title>
</head>
<body style="margin:0;padding:0;background:${C.paper2};">
<div style="display:none;max-height:0;overflow:hidden;opacity:0;">${escapeHtml(
    args.preheader,
  )}</div>
<table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%" style="background:${C.paper2};">
  <tr>
    <td align="center" style="padding:32px 16px;">
      <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="600" style="width:100%;max-width:600px;background:${C.paper};border:1px solid ${C.line};">
        <tr>
          <td style="padding:32px 32px 0;">
            ${
              identity.logoUrl
                ? `<img src="${escapeHtml(identity.logoUrl)}" alt="${escapeHtml(
                    identity.name,
                  )}" width="120" style="display:block;border:0;margin:0 0 28px;">`
                : `<div style="font-size:18px;letter-spacing:0.1em;text-transform:uppercase;color:${C.ink};margin:0 0 28px;">${escapeHtml(
                    identity.name,
                  )}</div>`
            }
            ${
              args.eyebrow
                ? `<div style="font-size:12px;letter-spacing:0.18em;text-transform:uppercase;color:${C.gold};margin:0 0 10px;">${escapeHtml(
                    args.eyebrow,
                  )}</div>`
                : ''
            }
            <h1 style="margin:0 0 24px;font-family:${FONT};font-size:26px;line-height:1.25;font-weight:400;color:${C.ink};">${escapeHtml(
              args.heading,
            )}</h1>
          </td>
        </tr>
        <tr><td style="padding:0 32px;font-family:${FONT};">${args.body}</td></tr>
        <tr>
          <td style="padding:28px 32px 32px;border-top:1px solid ${C.line};font-family:${FONT};">
            <p style="margin:0 0 6px;font-size:13px;line-height:1.6;color:${C.muted};">
              ${[
                `<strong style="color:${C.ink};font-weight:500;">${escapeHtml(identity.name)}</strong>`,
                escapeHtml(identity.addressLine),
                /* Each line only when there is something on it, and the middle
                   dot only when it has something on both sides. A blank field
                   used to render as an empty line and a stranded "·" — which
                   nobody saw until a message had to be written without the
                   company record to hand. */
                [
                  identity.phone &&
                    `<a href="tel:${escapeHtml(identity.phone.replace(/\s+/g, ''))}" style="color:${C.muted};text-decoration:none;">${escapeHtml(
                      identity.phone,
                    )}</a>`,
                  identity.email &&
                    `<a href="mailto:${escapeHtml(identity.email)}" style="color:${C.muted};text-decoration:none;">${escapeHtml(
                      identity.email,
                    )}</a>`,
                ]
                  .filter(Boolean)
                  .join(' · '),
              ]
                .filter(Boolean)
                .join('<br>')}
            </p>
            ${
              args.footNote
                ? `<p style="margin:12px 0 0;font-size:12px;line-height:1.6;color:${C.muted};">${escapeHtml(
                    args.footNote,
                  )}</p>`
                : ''
            }
          </td>
        </tr>
      </table>
    </td>
  </tr>
</table>
</body>
</html>`;
}

function button(label: string, url: string): string {
  if (!label || !url) return '';
  return `<table role="presentation" cellpadding="0" cellspacing="0" border="0" style="margin:8px 0 28px;">
    <tr><td style="background:${C.saffron};">
      <a href="${escapeHtml(url)}" style="display:inline-block;padding:14px 28px;font-family:${FONT};font-size:14px;letter-spacing:0.08em;text-transform:uppercase;color:#FFFFFF;text-decoration:none;">${escapeHtml(
        label,
      )}</a>
    </td></tr>
  </table>`;
}

